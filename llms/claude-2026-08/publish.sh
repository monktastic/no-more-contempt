#!/bin/sh
# Generates the website pages from manuscript/: index.md, book/, map/, appendix/,
# short/. They go to the repo root, where Jekyll finds them, and are not in
# git; the Actions build regenerates them on every push. Edit manuscript/ instead.
# --out DIR writes them somewhere else and leaves the guard and the read-only
# bits off, since nothing there is worth protecting from a stray edit.
cd "$(dirname "$0")" || exit 1
OUT=
case "$1" in
  --out) OUT=$2 ;;
  --out=*) OUT=${1#--out=} ;;
  '') ;;
  *) printf 'publish.sh: unknown option %s\n' "$1" >&2; exit 1 ;;
esac
[ -z "$OUT" ] || { mkdir -p "$OUT" || exit 1; OUT=$(cd "$OUT" && pwd); }
PUBLISH_OUT="$OUT" python3 - <<'PY'
import re, pathlib, shutil
from bookparts import (split_title, strip_todos, pages, start_here_counts,
                       BOOK_FILES, DRAFT_FILES, APPENDIX_FILES, TITLE_OVERRIDES)
import os
HERE = pathlib.Path('.').resolve()
ROOT = pathlib.Path(os.environ['PUBLISH_OUT']) if os.environ.get('PUBLISH_OUT') else HERE.parents[1]
GUARDED = not os.environ.get('PUBLISH_OUT')  # only the working copy needs the guard
MAN  = HERE / 'manuscript'
GEN  = '<!-- Generated by llms/claude-2026-08/publish.sh from manuscript/. Do not edit; edit the source. -->\n\n'

def page(path, title, order, permalink, body, parent=None, has_children=False, grand_parent=None):
    body = strip_todos(body)
    fm = ['---', f'title: "{title}"', f'nav_order: {order}', f'permalink: {permalink}']
    if parent: fm.append(f'parent: "{parent}"')
    if grand_parent: fm.append(f'grand_parent: "{grand_parent}"')
    if has_children: fm += ['has_children: true', 'has_toc: true']
    fm.append('---')
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists(): path.chmod(0o644)
    path.write_text('\n'.join(fm) + '\n\n' + GEN + '# ' + title + '\n\n' + body)
    if GUARDED:
        path.chmod(0o444)  # generated: read-only, so an edit here fails loudly
        written[str(path.relative_to(ROOT))] = sha(path)

# Refuse to overwrite a generated page that was edited after the last publish:
# that edit was made in the wrong place and would be lost. Port it to manuscript/
# first, or run with PUBLISH_FORCE=1 to discard it. The manifest records what
# the last publish wrote; if it's missing, the check is skipped.
import hashlib, json, sys
MANIFEST = HERE / '.publish-manifest.json'
def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()
if GUARDED and MANIFEST.exists() and not os.environ.get('PUBLISH_FORCE'):
    old = json.loads(MANIFEST.read_text())
    edited = [f for f, h in old.items() if (ROOT / f).exists() and sha(ROOT / f) != h]
    if edited:
        sys.exit('publish.sh: these generated pages were edited after the last publish; port the edits to '
                 'manuscript/ first, or PUBLISH_FORCE=1 to discard them:\n  ' + '\n  '.join(edited))
written = {}

for d in ('book', 'map', 'appendix', 'condensed', 'short'):
    p = ROOT / d
    if p.exists(): shutil.rmtree(p)

def words(*names):
    return sum(len((MAN / n).read_text().split()) for n in names)
def draft_words():
    return sum(len(strip_todos((MAN / n).read_text()).split()) for n in DRAFT_FILES)
bw, mw, dw = words(*BOOK_FILES), words('rest-of-book.md'), draft_words()
count_line = lambda w, what: f'*{what}: about {w:,} words, roughly {pages(w)} pages at 280 words a page. Updated whenever the site is regenerated.*\n\n'

# Start here
_, body = split_title((MAN / 'start-here.md').read_text())
body = start_here_counts(body, bw, mw)
page(ROOT / 'index.md', 'Start here', 1, '/', body)


# The book
page(ROOT / 'book' / 'index.md', 'The Book', 2, '/book/',
     count_line(bw, 'Preface through Chapter 5') + count_line(dw, 'Chapters 6 through 17, first drafts') + 'Preface through Chapter 5 is the short book, complete in itself. Chapters 6 onward are first drafts written by Claude from the author\'s notes, marked in red at the top of each; read them for the shape of the rest, not for the prose.\n',
     has_children=True)
chapters = [(f, TITLE_OVERRIDES.get(f)) for f in BOOK_FILES + DRAFT_FILES]
for i, (f, override) in enumerate(chapters, 1):
    t, body = split_title((MAN / f).read_text())
    line = count_line(len(strip_todos(body).split()), 'This chapter')
    if body.startswith('<p '):  # the draft banner stays first
        head, rest = body.split('\n', 1)
        body = head + '\n\n' + line + rest.lstrip('\n')
    else:
        body = line + body
    page(ROOT / 'book' / f, override or t, i, f'/book/{f[:-3]}/', body, parent='The Book')

# The map, split by Part
text = (MAN / 'rest-of-book.md').read_text()
chunks = re.split(r'\n(?=# Part [A-F])', text)
t, body = split_title(chunks[0])
page(ROOT / 'map' / 'index.md', 'Where This Goes', 4, '/map/', count_line(mw, 'Parts A to F') + body, has_children=True)
titles = {'F': 'Part F: What this book is for'}
for i, ch in enumerate(chunks[1:], 1):
    t, body = split_title(ch)
    letter = t.split()[1].rstrip(':')
    title = titles.get(letter, t)
    page(ROOT / 'map' / f'part-{letter.lower()}.md', title, i, f'/map/part-{letter.lower()}/', body, parent='Where This Goes')

# Appendices: part of the book, so nested under it, after the chapters
page(ROOT / 'appendix' / 'index.md', 'Appendices', len(chapters) + 1, '/appendix/',
     'For readers who want the machinery, the neighbouring thinkers, and the traditions.\n', parent='The Book', has_children=True)
for i, f in enumerate(APPENDIX_FILES, 1):
    t, body = split_title((MAN / f).read_text())
    page(ROOT / 'appendix' / f'{i}.md', t, i, f'/appendix/{i}/', body, parent='Appendices', grand_parent='The Book')

# The short version, for practitioners: its own manuscript directory. The
# preface is the section page; the chapters are its children.
SHORT = HERE / 'short-version-manuscript'
short_chapters = sorted(f for f in SHORT.glob('chapter-*.md'))
sw = sum(len(strip_todos(f.read_text()).split()) for f in short_chapters)
t, body = split_title((SHORT / 'preface.md').read_text())
page(ROOT / 'short' / 'index.md', t, 3, '/short/',
     count_line(sw, 'The short version') + body, has_children=True)
for i, f in enumerate(short_chapters, 1):
    t, body = split_title(f.read_text())
    title = t or f'Chapter {i}'
    page(ROOT / 'short' / f.name, title, i, f'/short/{f.stem}/', body, parent='The Short Version')

# The build stamp the site's footer shows, so a reader can say which version
# they're reading and a note can be tied back to a commit.
import subprocess, datetime
def git(*args):
    try:
        return subprocess.run(('git',) + args, capture_output=True, text=True,
                              cwd=HERE).stdout.strip()
    except OSError:
        return ''
(ROOT / '_data').mkdir(exist_ok=True)
(ROOT / '_data' / 'build.yml').write_text(
    'sha: "%s"\ndate: "%s"\n' % (git('rev-parse', '--short', 'HEAD') or 'unknown',
                                  datetime.date.today().strftime('%-d %B %Y')))

if GUARDED: MANIFEST.write_text(json.dumps(written, indent=1))
print('published: index.md, book/ (%d), short/ (%d), map/ (%d), appendix/ (4)' % (len(chapters) + 1, len(short_chapters) + 1, len(chunks)))
PY
