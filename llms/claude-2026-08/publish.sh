#!/bin/sh
# Generates the website pages from manuscript/. Output goes to the repo root
# (index.md, book/, map/, appendix/) and is committed, because GitHub Pages
# builds from the repo. Those files are generated; edit manuscript/ instead.
cd "$(dirname "$0")" || exit 1
python3 - <<'PY'
import re, pathlib, shutil
HERE = pathlib.Path('.').resolve()
ROOT = HERE.parents[1]
MAN  = HERE / 'manuscript'
GEN  = '<!-- Generated by llms/claude-2026-08/publish.sh from manuscript/. Do not edit; edit the source. -->\n\n'

def split_title(text):
    lines = text.split('\n')
    for i, l in enumerate(lines):
        if l.startswith('# '):
            return l[2:].strip(), ('\n'.join(lines[:i] + lines[i+1:])).strip() + '\n'
    return None, text.strip() + '\n'

def page(path, title, order, permalink, body, parent=None, has_children=False):
    fm = ['---', f'title: "{title}"', f'nav_order: {order}', f'permalink: {permalink}']
    if parent: fm.append(f'parent: "{parent}"')
    if has_children: fm += ['has_children: true', 'has_toc: true']
    fm.append('---')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(fm) + '\n\n' + GEN + '# ' + title + '\n\n' + body)

for d in ('book', 'map', 'appendix'):
    p = ROOT / d
    if p.exists(): shutil.rmtree(p)

def words(*names):
    return sum(len((MAN / n).read_text().split()) for n in names)
def pages(w): return int(round(w / 280.0))
BOOK_FILES = ['preface.md','chapter-1.md','chapter-1a.md','chapter-2.md','chapter-3.md','chapter-4.md','chapter-5.md']
bw, mw = words(*BOOK_FILES), words('rest-of-book.md')
count_line = lambda w, what: f'*{what}: about {w:,} words, roughly {pages(w)} pages at 280 words a page. Updated whenever the site is regenerated.*\n\n'

# Start here
_, body = split_title((MAN / 'start-here.md').read_text())
body = body.replace('It runs about fifty pages.', f'It runs about {pages(bw)} pages.')
body = body.replace('**The map**, called *Where This Goes*, is the rest of the book in outline:', f'**The map**, called *Where This Goes*, is the rest of the book in outline, about {pages(mw)} pages:')
page(ROOT / 'index.md', 'Start here', 1, '/', body)

# The book
page(ROOT / 'book' / 'index.md', 'The Book', 2, '/book/',
     count_line(bw, 'Preface through Chapter 5') + 'The short book, complete in itself. Read to the end of Chapter 5 before deciding whether you want the map.\n',
     has_children=True)
chapters = [('preface.md', None), ('chapter-1.md', None), ('chapter-1a.md', None),
            ('chapter-2.md', None), ('chapter-3.md', 'Chapter 3: The Sacrifice'),
            ('chapter-4.md', None), ('chapter-5.md', None)]
for i, (f, override) in enumerate(chapters, 1):
    t, body = split_title((MAN / f).read_text())
    page(ROOT / 'book' / f, override or t, i, f'/book/{f[:-3]}/', body, parent='The Book')

# The map, split by Part
text = (MAN / 'rest-of-book.md').read_text()
chunks = re.split(r'\n(?=# Part [A-F])', text)
t, body = split_title(chunks[0])
page(ROOT / 'map' / 'index.md', 'Where This Goes', 3, '/map/', count_line(mw, 'Parts A to F') + body, has_children=True)
titles = {'F': 'Part F: What this book is for'}
for i, ch in enumerate(chunks[1:], 1):
    t, body = split_title(ch)
    letter = t.split()[1].rstrip(':')
    title = titles.get(letter, t)
    page(ROOT / 'map' / f'part-{letter.lower()}.md', title, i, f'/map/part-{letter.lower()}/', body, parent='Where This Goes')

# Appendices
page(ROOT / 'appendix' / 'index.md', 'Appendices', 4, '/appendix/',
     'For readers who want the machinery, the neighbouring thinkers, and the traditions.\n', has_children=True)
for i, f in enumerate(['appendix-1-recursion.md', 'appendix-2-what-others-have-seen.md', 'appendix-3-the-traditions.md'], 1):
    t, body = split_title((MAN / f).read_text())
    page(ROOT / 'appendix' / f'{i}.md', t, i, f'/appendix/{i}/', body, parent='Appendices')

print('published: index.md, book/ (8), map/ (%d), appendix/ (4)' % len(chunks))
PY
